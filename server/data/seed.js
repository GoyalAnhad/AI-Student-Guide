async function seed() {
  try {
    await mongoose.connect(process.env.MONGO_URI);
    console.log("✅ Connected to MongoDB");

    await Promise.all([University.deleteMany({}), Career.deleteMany({}), Exam.deleteMany({})]);
    console.log("🗑️  Cleared existing data");

    await University.insertMany(universities);
    console.log(`✅ Inserted ${universities.length} universities`);

    await Exam.insertMany(exams);
    console.log(`✅ Inserted ${exams.length} exams`);

    await Career.insertMany(careers);
    console.log(`✅ Inserted ${careers.length} careers`);

    console.log("\n🎉 Database seeded successfully!\n");
    console.log("Next: node --env-file=.env data/seed.js");
    process.exit(0);
  } catch (err) {
    console.error("❌ Seeding failed:", err);
    process.exit(1);
  }
}

